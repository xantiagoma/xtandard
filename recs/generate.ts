// `bun run recs:generate`: validates recs/libraries.ts and writes the "Recommended Libraries"
// section of README.md (between the recs:start / recs:end markers), grouped by category.
// `--check` writes nothing and exits 1 when the README is out of date (run by `bun run check`
// and CI). The docs site renders the same data itself (site/src/components/RecommendedLibraries.tsx).
//
//   bun run recs:generate
//   bun recs/generate.ts --check
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { libraries } from "./libraries.ts";
import { categories, classifyLicense, npmUrl, repoUrl, type Recommendation } from "./schema.ts";

const root = fileURLToPath(new URL("../", import.meta.url));
const readmePath = `${root}README.md`;
const siteUrl = "https://me.xantiagoma.com/xtandard/project/recommended-libraries/";
const startMarker = "<!-- recs:start -->";
const endMarker = "<!-- recs:end -->";

// ---- validation -----------------------------------------------------------------------------

/** Every problem with the data, as messages (empty when valid). */
function validate(libs: Recommendation[], exportsMap: Record<string, unknown>): string[] {
  const errors: string[] = [];
  const modules = new Set(
    Object.keys(exportsMap).map((k) =>
      k === "." ? "@xtandard/lib" : `@xtandard/lib/${k.slice(2)}`,
    ),
  );
  const ids = new Set<string>(categories.map((c) => c.id));
  const seenNpm = new Set<string>();
  const seenName = new Set<string>();
  for (const lib of libs) {
    const at = `${lib.name || "(unnamed)"}:`;
    for (const key of ["name", "npm", "repo", "category", "provides", "why", "license"] as const) {
      if (!lib[key]?.trim()) errors.push(`${at} \`${key}\` is empty`);
    }
    if (seenNpm.has(lib.npm)) errors.push(`${at} npm package ${lib.npm} is listed twice`);
    if (seenName.has(lib.name.toLowerCase())) errors.push(`${at} name is listed twice`);
    seenNpm.add(lib.npm);
    seenName.add(lib.name.toLowerCase());
    if (!ids.has(lib.category)) errors.push(`${at} unknown category ${lib.category}`);
    if (!/^[\w.-]+\/[\w.-]+$/.test(lib.repo)) errors.push(`${at} repo must be "owner/name"`);
    if (lib.docs && !lib.docs.startsWith("https://"))
      errors.push(`${at} docs must be an https URL`);
    if (classifyLicense(lib.license) === "restrictive")
      errors.push(`${at} ${lib.license} is not a permissive license (see docs/RECOMMENDING.md)`);
    for (const p of lib.pairsWith ?? []) {
      if (!modules.has(p.module))
        errors.push(`${at} pairsWith ${p.module} is not an entry point in package.json`);
      if (!p.how.trim()) errors.push(`${at} pairsWith ${p.module} needs \`how\``);
    }
    for (const text of [lib.provides, lib.why, lib.caveat, lib.stable, lib.insteadOf]) {
      if (text?.includes("\n")) errors.push(`${at} keep prose fields on one line`);
    }
  }
  return errors;
}

// ---- Markdown -------------------------------------------------------------------------------

/** GitHub's heading anchor for plain-text headings like ours. */
const anchor = (heading: string) =>
  heading
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s-]/gu, "")
    .replace(/\s/g, "-");

function entry(lib: Recommendation): string[] {
  const links = [`[GitHub](${repoUrl(lib.repo)})`, `[npm](${npmUrl(lib.npm)})`];
  if (lib.docs) links.push(`[docs](${lib.docs})`);
  const npmNote = lib.npm === lib.name ? "" : ` (\`${lib.npm}\`)`;
  const lines = [
    `- **${lib.name}**${npmNote}: ${lib.provides} ${links.join(" · ")} · ${lib.license}`,
    `  - Why: ${lib.why}`,
  ];
  if (lib.insteadOf) lines.push(`  - Instead of: ${lib.insteadOf}`);
  for (const p of lib.pairsWith ?? []) lines.push(`  - Pairs with \`${p.module}\`: ${p.how}`);
  if (lib.caveat) lines.push(`  - Note: ${lib.caveat}`);
  if (lib.stable) lines.push(`  - Stable: ${lib.stable}`);
  return lines;
}

/** The generated block, markers included. */
function renderSection(libs: Recommendation[]): string {
  const used = categories.filter((c) => libs.some((l) => l.category === c.id));
  const out = [
    `${startMarker}`,
    "<!-- Generated by `bun run recs:generate` from recs/libraries.ts. Do not edit by hand. -->",
    "",
    `${libs.length} libraries in ${used.length} categories. Search and filter them, with each one's latest release and examples of using them with xtandard, on the [docs site](${siteUrl}). To suggest one, see [How to add a recommendation](./docs/RECOMMENDING.md).`,
    "",
    used.map((c) => `[${c.label}](#${anchor(c.label)})`).join(" · "),
  ];
  for (const c of used) {
    out.push("", `### ${c.label}`, "", c.blurb, "");
    const these = libs
      .filter((l) => l.category === c.id)
      .sort((a, b) => a.name.localeCompare(b.name, "en", { sensitivity: "base" }));
    for (const lib of these) out.push(...entry(lib));
  }
  out.push("", endMarker);
  return out.join("\n");
}

/** README with the generated block replaced (the markers must already be there). */
function replaceSection(readme: string, section: string): string {
  const start = readme.indexOf(startMarker);
  const end = readme.indexOf(endMarker);
  if (start < 0 || end < start)
    throw new Error(`README.md: missing the ${startMarker} … ${endMarker} markers`);
  return readme.slice(0, start) + section + readme.slice(end + endMarker.length);
}

// ---- run ------------------------------------------------------------------------------------

{
  const pkg = JSON.parse(readFileSync(`${root}package.json`, "utf8")) as {
    exports: Record<string, unknown>;
  };
  const errors = validate(libraries, pkg.exports);
  if (errors.length) {
    for (const e of errors) console.error(`recs: ${e}`);
    process.exit(1);
  }
  const readme = readFileSync(readmePath, "utf8");
  const next = replaceSection(readme, renderSection(libraries));
  if (process.argv.includes("--check")) {
    if (next !== readme) {
      console.error(
        "recs: README.md's Recommended Libraries section is out of date with recs/libraries.ts. Run `bun run recs:generate`.",
      );
      process.exit(1);
    }
    console.log(`recs: README.md is in sync (${libraries.length} libraries)`);
  } else {
    writeFileSync(readmePath, next);
    console.log(`recs: wrote ${libraries.length} libraries to README.md`);
  }
}
